def parse_frontmatter(text, label="<text>"):
    lines = text.splitlines()
    if not lines or lines[0] != "---":
        raise ValueError(f"{label}: missing frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ValueError(f"{label}: unterminated frontmatter") from None
    data = {}
    for line in lines[1:end]:
        if ":" not in line:
            raise ValueError(f"{label}: bad frontmatter line")
        key, value = line.split(":", 1)
        key = key.strip()
        if not key:
            raise ValueError(f"{label}: empty frontmatter key")
        if key in data:
            raise ValueError(f"{label}: duplicate {key}")
        value = value.strip()
        try:
            data[key] = json.loads(value)
        except json.JSONDecodeError:
            data[key] = value
    return data, "\n".join(lines[end + 1 :]).strip()


def frontmatter(path):
    return parse_frontmatter(Path(path).read_text(encoding="utf-8"), str(path))


def fragment_text(name, root=ROOT):
    if name not in FRAGMENT_NAMES:
        raise ValueError(f"unknown fragment {name!r}; known: {', '.join(FRAGMENT_NAMES)}")
    return (Path(root) / "fragments" / f"{name}.md").read_text(encoding="utf-8").strip()


def resolve_fragments(body, root=ROOT, label="<text>"):
    """Replace every `{{fragment:NAME}}` line with the fragment's text. One level only."""
    out = []
    for line in body.splitlines():
        m = FRAGMENT_RE.fullmatch(line.strip())
        if m:
            text = fragment_text(m.group(1), root)
            if any(FRAGMENT_RE.fullmatch(inner.strip()) for inner in text.splitlines()):
                raise ValueError(f"{label}: fragment {m.group(1)} may not include another fragment")
            out.append(text)
        elif "{{fragment:" in line:
            raise ValueError(f"{label}: fragment marker must be alone on its line: {line.strip()}")
        else:
            out.append(line)
    return "\n".join(out)


def load_roles(root=ROOT):
    roles = []
    for f in sorted((Path(root) / "roles").glob("*.md")):
        meta, body = frontmatter(f)
        meta = dict(meta)
        meta["source"] = body
        meta["body"] = resolve_fragments(body, root, str(f))
        meta["file"] = f.name
        roles.append(meta)
    return roles


def load_packs(root=ROOT):
    packs = []
    for f in sorted((Path(root) / "packs").glob("*/PACK.md")):
        meta, body = frontmatter(f)
        meta = dict(meta)
        meta["body"] = body
        meta["dir"] = f.parent.name
        packs.append(meta)
    return packs


